#!/usr/bin/env node
// scripts/gen-tenant-tables.mjs
//
// Derives the tenant-scoping table lists in eslint-rules/tenant-tables.mjs from
// the migrations, which are the only source of truth for the schema.
//
// A table is TENANT_SCOPED if it has a restaurant_id column — that column is the
// tenant boundary, so every query against the table must constrain it.
// Everything else is either global (shared across tenants) or a child table that
// inherits its tenant through a parent FK; both are listed separately so the
// lint rule stays silent on them and a reviewer can see the classification.
//
// Run after any migration that adds a table or a restaurant_id column:
//   node scripts/gen-tenant-tables.mjs

import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const migrationsDir = join(root, 'supabase', 'migrations')
const out = join(root, 'eslint-rules', 'tenant-tables.mjs')

const sql = readdirSync(migrationsDir)
    .filter(f => f.endsWith('.sql'))
    .sort()
    .map(f => readFileSync(join(migrationsDir, f), 'utf8'))
    .join('\n')

// Matches both `public.foo` and `"public"."foo"`, quoted or bare.
const TBL = '(?:"?public"?\\s*\\.\\s*)?"?([a-z_0-9]+)"?'

const bodies = new Map()
const createRe = new RegExp(
    `CREATE\\s+TABLE\\s+(?:IF\\s+NOT\\s+EXISTS\\s+)?${TBL}\\s*\\(([\\s\\S]*?)\\n\\s*\\);`,
    'gi'
)
for (const m of sql.matchAll(createRe)) {
    bodies.set(m[1], (bodies.get(m[1]) ?? '') + m[2])
}

// A restaurant_id added later by ALTER TABLE counts just the same.
const altered = new Set()
const alterRe = new RegExp(
    `ALTER\\s+TABLE\\s+(?:IF\\s+EXISTS\\s+)?${TBL}\\s+ADD\\s+COLUMN\\s+(?:IF\\s+NOT\\s+EXISTS\\s+)?"?restaurant_id"?`,
    'gi'
)
for (const m of sql.matchAll(alterRe)) altered.add(m[1])

// A dropped table is no longer part of the schema.
const dropped = new Set()
const dropRe = new RegExp(`DROP\\s+TABLE\\s+(?:IF\\s+EXISTS\\s+)?${TBL}`, 'gi')
for (const m of sql.matchAll(dropRe)) dropped.add(m[1])

const scoped = []
const unscoped = []
for (const [name, body] of [...bodies].sort(([a], [b]) => a.localeCompare(b))) {
    if (dropped.has(name)) continue
    if (/"?restaurant_id"?/.test(body) || altered.has(name)) scoped.push(name)
    else unscoped.push(name)
}
for (const name of [...altered].sort()) {
    if (!bodies.has(name) && !dropped.has(name) && !scoped.includes(name)) scoped.push(name)
}
scoped.sort()

const list = names => names.map(n => `    '${n}',`).join('\n')

writeFileSync(out, `// eslint-rules/tenant-tables.mjs
//
// GENERATED by scripts/gen-tenant-tables.mjs — do not edit by hand.
// Re-run that script after any migration that adds a table or a restaurant_id
// column, and commit the result alongside the migration.

/**
 * Tables carrying a restaurant_id column. Every query against one of these must
 * constrain restaurant_id — see the require-tenant-scope rule.
 */
export const TENANT_SCOPED_TABLES = new Set([
${list(scoped)}
])

/**
 * Tables with no restaurant_id. Two kinds, deliberately not distinguished by the
 * lint rule because neither can be scoped by a restaurant_id filter:
 *
 *   • global      — shared across every tenant (roles, subscription_plans, …)
 *   • child rows  — tenant inherited through a parent FK (order_items → orders)
 *
 * Child rows are the residual risk the rule cannot cover: reaching them by
 * parent id is only safe if that parent was itself tenant-checked first.
 */
export const UNSCOPED_TABLES = new Set([
${list(unscoped)}
])
`)

console.log(`${out}: ${scoped.length} tenant-scoped, ${unscoped.length} unscoped`)
